#!/usr/bin/env python3
"""
Put back catalog rows the load ledger says exist and the catalog lacks.

    python etl/restore_ledger_catalog.py                    # report only
    python etl/restore_ledger_catalog.py --write            # append the rows
    make reindex reload-corpus                              # then

WHY. etl/data_manifest.yaml records, per load, the `catalog_labels` it added.
On 2026-11-11 none of the 31 recorded for CDC SVI (county) and WorldPop were in
backend/geoark_attributes.csv, nor in the last commit: something rewrote the
catalog after the 2026-10-16 ingests and dropped them, and nothing noticed.
Their values were loaded and resolvable (attribute_source), so every plan
could run on them and retrieval could never find them: "tract poverty in St.
Louis" fell back to an ACS county table.

WHAT IS RESTORED. One row per missing label, built the way etl/ingest.py's
table path builds it: description from the dataset's sidecar (else the
database's), years from geo_measure. The original tags were generated by the
tagger model and are LOST with the rows; tags here are the description's own
words (load_county_values.tags_for), and the report says so. Re-tag with
`make ingest ... --replace` if the model tags matter.

Runs on the host (the catalog is mounted read-only in the containers) and
reads the database through `docker exec`, like eval/answer_probe.py.
"""

from __future__ import annotations

import argparse
import csv
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).parent))
from load_county_values import tags_for  # noqa: E402

LEDGER = ROOT / "etl" / "data_manifest.yaml"
CATALOG = ROOT / "backend" / "geoark_attributes.csv"
INCOMING = ROOT / "deploy" / "incoming"


def psql(sql: str, container: str) -> list[list[str]]:
    p = subprocess.run(
        ["docker", "exec", "-i", container, "sh", "-c",
         'psql -U "${POSTGRES_USER:-postgres}" -d "${POSTGRES_DB:-mygisdb}" -X -q -At -F "\t"'],
        input=sql, capture_output=True, text=True, encoding="utf-8")
    if p.returncode != 0:
        raise RuntimeError(p.stderr.strip())
    return [line.split("\t") for line in p.stdout.splitlines() if line]


def sidecar_desc(entry: dict) -> dict[str, str]:
    """column -> description from the sidecar recorded in the ledger entry."""
    out = {}
    for f in entry.get("files") or []:
        if f["path"].endswith(".meta.yaml"):
            meta = yaml.safe_load((INCOMING / f["path"]).read_text(encoding="utf-8")) or {}
            for col, spec in (meta.get("columns") or {}).items():
                if isinstance(spec, dict) and spec.get("desc"):
                    out[col] = str(spec["desc"]).strip()
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--db-container", default="geoark-db-1")
    args = ap.parse_args()

    ledger = yaml.safe_load(LEDGER.read_text(encoding="utf-8"))
    with CATALOG.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.reader(fh))
    header = rows[0]
    present = {r[header.index("attr_label")] for r in rows[1:] if r}

    missing = []
    for e in ledger.get("datasets") or []:
        labels = [l for l in (e.get("catalog_labels") or []) if l not in present]
        if labels:
            missing.append((e, labels))
    if not missing:
        print("  every ledger catalog label is in the catalog")
        return 0

    codes = sorted({l for _, ls in missing for l in ls})
    lit = ",".join("'" + c.replace("'", "''") + "'" for c in codes)
    db = {r[0]: r[1:] for r in psql(
        f"SELECT a.attr_id, COALESCE(a.description, ''), min(m.min_year), max(m.max_year) "
        f"FROM attribute_source a JOIN geo_measure m ON m.code = a.attr_id AND m.level = 'county' "
        f"WHERE a.attr_id IN ({lit}) GROUP BY 1, 2;", args.db_container)}

    new = []
    for e, labels in missing:
        side = sidecar_desc(e)
        prefix = (e.get("dataset_id") or "") + "::"
        for code in labels:
            if code not in db:
                print(f"  SKIP {code}: no county values in geo_measure")
                continue
            desc_db, y0, y1 = db[code]
            column = code.split("_", 1)[1] if "_" in code else code
            desc = side.get(column) or desc_db or column
            row = dict.fromkeys(header, "")
            row.update({
                "dataset_id": e["dataset_id"], "dataset_clean": e["name"],
                "attr_label": code, "attr_orig": column, "attr_desc": desc,
                "attr_id": code, "start_date": y0, "end_date": y1,
                "spatial_rep": "POLYGON", "entity_type": "COUNTY",
                "tags": str(tags_for(desc)),
            })
            new.append(row)
            print(f"  {e['id']:<22} {code:<18} {desc[:70]}")
    print(f"\n  {len(new)} rows missing from {CATALOG.name}"
          f" (tags rebuilt from descriptions; the tagger's originals are lost)")
    if args.write and new:
        with CATALOG.open("a", encoding="utf-8", newline="") as fh:
            csv.writer(fh, lineterminator="\r\n").writerows([[r[c] for c in header] for r in new])
        print("  appended -> make reindex reload-corpus")
    elif new:
        print("  report only; --write to append")
    return 0


if __name__ == "__main__":
    sys.exit(main())
